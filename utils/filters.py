def is_junk(text):
    """Проверяет является ли текст мусорным"""
    t = text.lower()

    # Содержит мусорные слова
    for word in JUNK_WORDS:
        if word in t:
            return True

    # Это email
    if "@" in t and "." in t and len(t) < 50:
        return True

    # Это телефон (только цифры, +, -, пробелы)
    clean = t.replace("+", "").replace("-", "").replace(" ", "").replace("(", "").replace(")", "")
    if clean.isdigit() and len(clean) >= 7:
        return True

    return False