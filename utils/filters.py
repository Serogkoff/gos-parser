def is_junk(text):
    t = text.lower()

    for word in JUNK_WORDS:
        if word in t:
            return True

    if "@" in t and "." in t and len(t) < 50:
        return True

    clean = t.replace("+", "").replace("-", "").replace(" ", "").replace("(", "").replace(")", "")
    if clean.isdigit() and len(clean) >= 7:
        return True

    return False